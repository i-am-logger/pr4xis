    /// A `LexicalReasoner` that delegates EVERY method to a wrapped
    /// `ComposedReasoner` — the real production reasoner, not a synthetic
    /// stub — except [`conditional_rule_for_predicate`](LexicalReasoner::
    /// conditional_rule_for_predicate), which records the predicate string
    /// it was called with instead of returning a rule. Proves the GRAMMAR
    /// half of task #27 (real English collapses "eligible for" into a
    /// relational predicate) independently of the STILL-unwired production
    /// `conditional_rule_for_predicate` (task #28's job).
    struct PredicateCapture<'a> {
        composed: &'a pr4xis_domains::cognitive::linguistics::composed::ComposedReasoner,
        captured: std::cell::RefCell<Vec<String>>,
    }

    impl LexicalReasoner for PredicateCapture<'_> {
        fn lookup(&self, word: &str) -> &[ConceptId] {
            self.composed.lookup(word)
        }
        fn concept(
            &self,
            id: ConceptId,
        ) -> Option<pr4xis_domains::cognitive::linguistics::english::ConceptView<'_>> {
            self.composed.concept(id)
        }
        fn concept_by_synset(
            &self,
            synset_id: &str,
        ) -> Option<pr4xis_domains::cognitive::linguistics::english::ConceptView<'_>> {
            self.composed.concept_by_synset(synset_id)
        }
        fn parents(&self, id: ConceptId) -> &[ConceptId] {
            self.composed.parents(id)
        }
        fn children(&self, id: ConceptId) -> &[ConceptId] {
            self.composed.children(id)
        }
        fn is_a(&self, child: ConceptId, ancestor: ConceptId) -> bool {
            self.composed.is_a(child, ancestor)
        }
        fn ancestors(&self, id: ConceptId) -> Vec<ConceptId> {
            self.composed.ancestors(id)
        }
        fn common_ancestor(&self, a: ConceptId, b: ConceptId) -> Option<ConceptId> {
            self.composed.common_ancestor(a, b)
        }
        fn ancestor_chain(&self, child: ConceptId, ancestor: ConceptId) -> Option<Vec<ConceptId>> {
            self.composed.ancestor_chain(child, ancestor)
        }
        fn concept_count(&self) -> pr4xis_domains::formal::math::quantity::value::Quantity {
            self.composed.concept_count()
        }
        fn max_surface_words(&self) -> usize {
            self.composed.max_surface_words()
        }
        fn lookup_case_folded(&self, word: &str) -> Vec<ConceptId> {
            self.composed.lookup_case_folded(word)
        }
        fn is_function_word(&self, word: &str) -> bool {
            self.composed.is_function_word(word)
        }
        fn relation_for_surface(
            &self,
            surface: &str,
        ) -> Option<pr4xis_runtime::ontology::ConceptRef> {
            self.composed.relation_for_surface(surface)
        }
        fn ontology_of_concept(
            &self,
            id: ConceptId,
        ) -> Option<pr4xis::ontology::meta::OntologyName> {
            self.composed.ontology_of_concept(id)
        }
        fn is_loaded_surface(&self, surface: &str) -> bool {
            self.composed.is_loaded_surface(surface)
        }
        fn conditional_rule_for_predicate(
            &self,
            predicate: &str,
            _object: &str,
        ) -> Option<pr4xis_domains::social::judicial::conditional_rule::ConditionalRule> {
            self.captured.borrow_mut().push(predicate.to_string());
            None
        }
    }

