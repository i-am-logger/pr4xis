//! The generated chat-capability suite — a pure functor from a loaded reasoner
//! graph to `{(question, expected-property)}`, plus a structural faithfulness
//! checker over the chat pipeline's [`ProcessResult`].
//!
//! Nothing in this module knows a single concept name. The corpus is the dense
//! walk `0 .. reasoner.concept_count()` over `&dyn LexicalReasoner`
//! (`probe_cases`); English + every loaded `.prx` + USC fall out of the SAME
//! loop, partitioned only by [`LexicalReasoner::ontology_of_concept`]. Every
//! `question` is realized by the grammar's frame-generator (`Frames`, in the
//! realization ontology) from typed args — the generator writes no interrogative
//! text. Every `expected` value is READ FROM THE GRAPH (a gloss from
//! `concept(id).definitions()`, an ancestor's own lemma, the derived `known`
//! set) — no expected answer string is authored here.
//!
//! `check` asserts a STRUCTURAL property over the turn's typed
//! [`ChatOutcome`], its `unresolved` set, and — for affirm/deny/gap surfaces —
//! reference strings RE-GENERATED by the realization ontology (`realize::*`),
//! never a literal answer template. In particular a turn that claims not to know
//! a KNOWN concept (`"I do not know the words cat, dog"` over a non-edge of two
//! known concepts) is scored a FALSE-NEGATION failure, not a pass — the honesty
//! core (Reiter 1978 closed-world: an abstention names only genuinely-unknown
//! surfaces).
//!
//! The witness-scale `ChatFaithfullyRealizesTheOntology` axiom carries the
//! CLEAN core (define / is-a / directional-No) over the sample graph as a
//! registered, gate-swept green sentinel; the corpus lane
//! (`praxis-corpus-tests/tests/chat_capability.rs`) runs the FULL battery
//! including the non-edge honesty class over the real corpus, where the teeth
//! (and the current red) live.

