// =========================================================================
// The generated case — (question, provenance, expected faithfulness property)
// =========================================================================

/// One generated probe: a question realized by the grammar, the exact graph
/// construct that produced it (provenance), and the faithfulness property the
/// chat's answer must carry.
pub struct ProbeCase {
    /// The question surface — realized by `Frames` from typed args, NEVER a
    /// literal in the generator.
    pub question: String,
    /// The exact edge / node the walk read to produce this case.
    pub construct: Construct,
    /// The structural property `check` asserts over the turn.
    pub expected: Expected,
}

/// The graph construct a probe was derived from — its provenance. The `source`
/// on [`Construct::Definition`] is `ontology_of_concept`, so a legal/USC case is
/// recognized as its own stratum with no source-specific code path.
pub enum Construct {
    /// A concept that carries a gloss → a "what is X" define probe.
    Definition {
        id: ConceptId,
        source: Option<OntologyName>,
    },
    /// A true is-a pair `child ⊑ ancestor` (from `ancestors`) → an affirming
    /// polar probe.
    IsAPositive {
        child: ConceptId,
        ancestor: ConceptId,
    },
    /// The REVERSE of a strict edge `child ⊑ parent` → a provable-No polar probe
    /// (`(parent, child)`; Subsumption is antisymmetric).
    IsADirectionalNo { parent: ConceptId, child: ConceptId },
    /// A seeded pair with no is-a/opposition path either way → a
    /// denies-or-abstains probe (never a false Yes, never a false vocab-gap).
    NonEdge { a: ConceptId, b: ConceptId },
    // Relational { child, parent, kind } and QualityValue { id } are NOT built:
    // Parthood/grounding positives are not enumerable through the current
    // `LexicalReasoner` surface (only `reaches`-answerable, not edge-listable),
    // and there is no quality/quantity accessor on the trait. Both are flagged in
    // the module report; a quality-bearing concept degrades to the Definition
    // class (honest — no fabricated value question).
}

impl Construct {
    /// The stratum name, for the corpus lane's per-class failure breakdown.
    pub fn class_name(&self) -> &'static str {
        match self {
            Construct::Definition { .. } => "define",
            Construct::IsAPositive { .. } => "is-a",
            Construct::IsADirectionalNo { .. } => "directional-No",
            Construct::NonEdge { .. } => "non-edge",
        }
    }
}

/// The faithfulness property to check — every value read from the graph, never
/// an authored answer string.
pub enum Expected {
    /// `Answered` and the response carries the concept's own gloss.
    ContainsGloss(String),
    /// `Answered` and the response realizes the affirmative is-a sentence
    /// "`subject` is a `target`" (the SAME precise surface production uses to
    /// answer a polar is-a question — `realize::sentence_relation(subject,
    /// target, None)`), without claiming ignorance of the target. Checking
    /// this exact sentence rather than a bare substring of `target` closes a
    /// gate-invisible hole: a long define-style response can happen to
    /// mention the target's label for an unrelated reason (e.g. inside its
    /// own gloss text) without ever asserting the is-a relation.
    Affirms { subject: String, target: String },
    /// The response realizes the negation of "`subject` is-a `object`" (the two
    /// endpoints of the reversed strict edge) — a provable No.
    DeniesDirectional { subject: String, object: String },
    /// Never a false Yes over the pair, never a claim of ignorance about the
    /// KNOWN concepts, never a known concept leaked into `unresolved`. An honest
    /// abstain (or a provable No) passes.
    DeniesOrAbstains { known: Vec<String> },
    /// The honest-abstention property alone (same predicate as
    /// [`Expected::DeniesOrAbstains`], for a seeded pair known to have no path):
    /// abstains over KNOWN entities without a false vocab-gap.
    Abstains { known: Vec<String> },
}

// =========================================================================
// The per-case structural verdict
// =========================================================================

/// The verdict of a single `check` — pass, or fail carrying the structural
/// reason (used to build the corpus lane's class/count breakdown). A local,
/// comparable verdict: the registered [`Axiom`] lifts it to a
/// [`pr4xis::logic::proof::Verdict`] at its boundary.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Verdict {
    Pass,
    Fail(String),
}

impl Verdict {
    pub fn pass() -> Self {
        Verdict::Pass
    }

    pub fn is_pass(&self) -> bool {
        matches!(self, Verdict::Pass)
    }
}

