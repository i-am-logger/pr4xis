// (3) THE GENERIC FAITHFULNESS CHECKER — structural, never string-equality
// =========================================================================

/// Fold a surface to a comparison form: lowercase, every non-alphanumeric char
/// (quotes, commas, periods) → a space, whitespace collapsed. So a
/// realizer-generated reference string matches the pipeline's response modulo
/// punctuation and spacing, never demanding a byte-exact answer template.
fn normalize(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    let mut prev_space = true;
    for ch in s.chars() {
        if ch.is_alphanumeric() {
            for c in ch.to_lowercase() {
                out.push(c);
            }
            prev_space = false;
        } else if !prev_space {
            out.push(' ');
            prev_space = true;
        }
    }
    if out.ends_with(' ') {
        out.pop();
    }
    out
}

fn contains_norm(haystack: &str, needle: &str) -> bool {
    let n = normalize(needle);
    if n.is_empty() {
        return false;
    }
    normalize(haystack).contains(&n)
}

fn answered(result: &ProcessResult) -> bool {
    matches!(result.outcome, ChatOutcome::Answered)
}

/// The realizer's OWN vocabulary-gap surface for a set of labels — the exact
/// "I do not know the word(s) …" string [`realize::realize`] emits for an
/// `UnknownVocabulary` frame naming those entities. Re-generated from the
/// realization ontology, so detecting it is structural (a frame identity), not an
/// authored answer literal.
fn realizer_gap_surface(labels: &[String]) -> String {
    let mut content = ResponseContent::new(ResponseFrame::UnknownVocabulary);
    for l in labels {
        content = content.with_entity(l);
    }
    realize::realize(&content)
}

/// Does the response claim ignorance of a KNOWN concept? — the FALSE-NEGATION
/// core. True iff the response contains the realizer's gap surface over any
/// non-empty subset of the known labels (the whole set, as the abstain branch
/// names them, or any single known label). A concept the graph KNOWS must never
/// be surfaced as an unknown word.
fn claims_ignorance_of_known(result: &ProcessResult, known: &[String]) -> bool {
    if known.is_empty() {
        return false;
    }
    // The full-set gap surface (the abstain branch names every queried entity).
    if contains_norm(&result.response, &realizer_gap_surface(known)) {
        return true;
    }
    // Any single known label surfaced as an unknown word.
    known
        .iter()
        .any(|k| contains_norm(&result.response, &realizer_gap_surface(&core_slice(k))))
}

fn core_slice(k: &str) -> Vec<String> {
    vec![k.to_owned()]
}

/// Did a KNOWN concept leak into the typed `unresolved` set? — the structural
/// mirror of the false-negation on [`ChatOutcome::Abstained`]. An abstention
/// must name only genuinely-unknown surfaces.
fn leaks_known_into_unresolved(result: &ProcessResult, known: &[String]) -> bool {
    match &result.outcome {
        ChatOutcome::Abstained { unresolved } => unresolved
            .iter()
            .any(|u| known.iter().any(|k| normalize(k) == normalize(u))),
        ChatOutcome::Answered => false,
        // A rule-governed turn never populates `unresolved` at all — the
        // structural mirror does not apply.
        ChatOutcome::Conditional { .. } | ChatOutcome::RuleResolved { .. } => false,
    }
}

/// Does the response FALSELY affirm one of the pair is-a the other? — the guard
/// that a non-edge is never answered with a fabricated Yes. Checks the
/// realizer's affirmative copula surface for both orders.
fn false_affirms_pair(result: &ProcessResult, known: &[String]) -> bool {
    if known.len() < 2 {
        return false;
    }
    let a = &known[0];
    let b = &known[1];
    let fwd = realize::sentence_relation(a, b, None);
    let rev = realize::sentence_relation(b, a, None);
    answered(result)
        && (contains_norm(&result.response, &fwd) || contains_norm(&result.response, &rev))
}

/// THE STRUCTURAL CHECKER: evaluate the expected faithfulness property against
/// the turn's typed [`ChatOutcome`], its `unresolved` set, and realizer-generated
/// reference surfaces — never a hardcoded answer.
pub fn check(result: &ProcessResult, expected: &Expected) -> Verdict {
    match expected {
        Expected::ContainsGloss(gloss) => {
            if !answered(result) {
                Verdict::Fail("define: abstained instead of answering".into())
            } else if contains_norm(&result.response, gloss) {
                Verdict::Pass
            } else {
                Verdict::Fail("define: response does not carry the concept's gloss".into())
            }
        }
        Expected::Affirms { subject, target } => {
            let affirmation = realize::sentence_relation(subject, target, None);
            if !answered(result) {
                Verdict::Fail("is-a: abstained on a true is-a edge".into())
            } else if claims_ignorance_of_known(result, core_slice(target).as_slice()) {
                Verdict::Fail("is-a: claims ignorance of a KNOWN ancestor".into())
            } else if contains_norm(&result.response, &affirmation) {
                Verdict::Pass
            } else {
                Verdict::Fail(
                    "is-a: response does not realize the affirmative is-a sentence".into(),
                )
            }
        }
        Expected::DeniesDirectional { subject, object } => {
            let neg = realize::realize_negation(subject, object, None);
            let affirm = realize::sentence_relation(subject, object, None);
            if contains_norm(&result.response, &neg) {
                Verdict::Pass
            } else if answered(result) && contains_norm(&result.response, &affirm) {
                Verdict::Fail("directional-No: FALSE Yes on the reverse of a strict edge".into())
            } else {
                Verdict::Fail("directional-No: did not realize the provable negation".into())
            }
        }
        Expected::DeniesOrAbstains { known } | Expected::Abstains { known } => {
            if false_affirms_pair(result, known) {
                Verdict::Fail("non-edge: FALSE Yes over an unrelated pair".into())
            } else if claims_ignorance_of_known(result, known) {
                Verdict::Fail("non-edge: FALSE NEGATION — claims not to know KNOWN concepts".into())
            } else if leaks_known_into_unresolved(result, known) {
                Verdict::Fail("non-edge: a KNOWN concept leaked into `unresolved`".into())
            } else {
                // Honest abstain or a provable No — both faithful.
                Verdict::Pass
            }
        }
    }
}

/// Run one probe end-to-end and check it. `lang` is the linguistic substrate
/// (tokenize / parse), `reasoner` the lexical-reasoning surface.
pub fn run_case(lang: &English, reasoner: &dyn LexicalReasoner, case: &ProbeCase) -> Verdict {
    let result = process_with_reasoner(lang, reasoner, &case.question);
    check(&result, &case.expected)
}

/// A per-class tally of failures — the corpus lane's RED breakdown.
#[derive(Debug, Default, Clone)]
pub struct FailureBreakdown {
    pub define: usize,
    pub is_a: usize,
    pub directional_no: usize,
    pub non_edge: usize,
    pub total: usize,
    /// A few example (question → reason) lines, for the panic message.
    pub examples: Vec<String>,
}

impl FailureBreakdown {
    fn record(&mut self, case: &ProbeCase, why: &str) {
        match case.construct {
            Construct::Definition { .. } => self.define += 1,
            Construct::IsAPositive { .. } => self.is_a += 1,
            Construct::IsADirectionalNo { .. } => self.directional_no += 1,
            Construct::NonEdge { .. } => self.non_edge += 1,
        }
        self.total += 1;
        if self.examples.len() < 12 {
            self.examples.push(format!(
                "[{}] {:?} — {}",
                case.construct.class_name(),
                case.question,
                why
            ));
        }
    }

    pub fn is_empty(&self) -> bool {
        self.total == 0
    }

    pub fn summary(&self) -> String {
        format!(
            "{} define, {} is-a, {} directional-No, {} non-edge (false-negation / false-Yes / gloss-miss) — {} total",
            self.define, self.is_a, self.directional_no, self.non_edge, self.total
        )
    }
}

/// Run the whole generated suite over a reasoner and collect the per-class
/// failure breakdown — the shared driver for both the witness axiom and the
/// corpus `#[test]`.
pub fn evaluate(
    lang: &English,
    reasoner: &dyn LexicalReasoner,
    frames: &Frames,
    budget: SampleBudget,
) -> FailureBreakdown {
    let mut breakdown = FailureBreakdown::default();
    for case in probe_cases(reasoner, frames, budget) {
        if let Verdict::Fail(why) = run_case(lang, reasoner, &case) {
            breakdown.record(&case, &why);
        }
    }
    breakdown
}

/// Corpus-scale counterpart to [`evaluate`] — same generation + structural
/// check, parallelized across `std::thread::available_parallelism()` worker
/// threads (the native `std::thread::scope` pattern proven in
/// `pr4xis_domains`'s `compute_defines_overlay`, no new dependency).
///
/// A production reasoner (e.g. `ComposedReasoner`) holds `Vec<Rc<
/// RuntimeOntology>>` — `Rc`, not `Sync` — so a single instance cannot be
/// shared by reference across worker threads the way [`evaluate`] shares
/// `reasoner: &dyn LexicalReasoner` in the single-threaded case. Instead the
/// caller supplies `build_reasoner`, called ONCE to generate the case list
/// (a cheap, pure structural walk over the graph — case generation itself
/// does not run the chat pipeline) and then ONCE PER WORKER THREAD (each
/// thread builds and keeps its own owned reasoner instance, never shared)
/// to run that worker's chunk of cases through the actual pipeline
/// (`run_case`), which is the expensive per-item cost this function
/// parallelizes.
///
/// Chunks are joined back in ORIGINAL chunk order — exactly like
/// `compute_defines_overlay`'s `flat_map` over its spawned handles — so the
/// assembled failure list is in the SAME order `evaluate`'s serial scan
/// would produce, regardless of thread scheduling. That determinism matters
/// beyond the per-class counts: `FailureBreakdown::record` caps `examples`
/// at the first 12 failures in scan order, so an out-of-order merge would
/// silently admit or drop different examples than the serial run. Building
/// the full ordered failure list first and only then folding it through
/// `record` (rather than recording per-chunk and merging partial
/// `FailureBreakdown`s) reproduces the serial scan's exact example list as
/// well as its exact per-class counts.
pub fn evaluate_parallel<R: LexicalReasoner>(
    lang: &English,
    build_reasoner: impl Fn() -> R + Sync + Send,
    frames: &Frames,
    budget: SampleBudget,
) -> FailureBreakdown {
    let generation_reasoner = build_reasoner();
    let cases: Vec<ProbeCase> = probe_cases(&generation_reasoner, frames, budget).collect();
    drop(generation_reasoner);

    let worker_count = std::thread::available_parallelism()
        .map(core::num::NonZeroUsize::get)
        .unwrap_or(1)
        .min(cases.len().max(1));

    let build_reasoner = &build_reasoner;
    let failures: Vec<(&ProbeCase, String)> = if worker_count <= 1 {
        run_chunk(lang, build_reasoner, &cases)
    } else {
        let chunk_size = cases.len().div_ceil(worker_count);
        std::thread::scope(|scope| {
            cases
                .chunks(chunk_size)
                .map(|chunk| scope.spawn(move || run_chunk(lang, build_reasoner, chunk)))
                .collect::<Vec<_>>()
                .into_iter()
                .flat_map(|handle| {
                    handle
                        .join()
                        .expect("evaluate_parallel worker thread panicked")
                })
                .collect()
        })
    };

    let mut breakdown = FailureBreakdown::default();
    for (case, why) in failures {
        breakdown.record(case, &why);
    }
    breakdown
}

/// One worker's unit of work for [`evaluate_parallel`]: build ONE owned
/// reasoner (never shared across threads) and run it over `chunk`'s cases in
/// order, returning only the failures — a plain `fn` (not a closure) so the
/// `&'a ProbeCase` output lifetime elides against `chunk: &'a [ProbeCase]`
/// the way closures cannot reliably infer on their own.
fn run_chunk<'a, R: LexicalReasoner>(
    lang: &English,
    build_reasoner: &(impl Fn() -> R + Sync),
    chunk: &'a [ProbeCase],
) -> Vec<(&'a ProbeCase, String)> {
    let reasoner = build_reasoner();
    chunk
        .iter()
        .filter_map(|case| match run_case(lang, &reasoner, case) {
            Verdict::Fail(why) => Some((case, why)),
            Verdict::Pass => None,
        })
        .collect()
}

