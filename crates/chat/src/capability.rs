// (1) THE GENERIC GENERATOR — a pure functor `reasoner → iterator of ProbeCase`
// =========================================================================

/// Seeded, stratified, bounded sampling of the concept space — deterministic
/// run-to-run. A stride over `0..concept_count()` (spread across the id space,
/// not biased to low ids) plus per-class caps; the non-edge partner offset is
/// seeded so the pairing is reproducible and auditable.
#[derive(Debug, Clone, Copy)]
pub struct SampleBudget {
    seed: u64,
    /// Target number of concept ids to visit (the stride is `count / target`).
    target_ids: usize,
    /// Max probes emitted per class (bounds the per-turn pipeline cost).
    per_class: usize,
    /// Emit non-edge probes (the honesty class). The witness sentinel omits it
    /// (its teeth are the corpus lane); the corpus lane includes it.
    include_nonedge: bool,
    /// Emit the reverse-edge directional-No class.
    include_directional_no: bool,
    /// Restrict the define class to NOMINAL concepts. RETIRED to `false` in
    /// both lanes since the verb-definition frame + its extraction path exist
    /// (a verb concept is asked over its gerundial nominal, "what is
    /// coughing") — the witness sentinel now tests that capability instead of
    /// filtering it out. Kept as a field so a future POS slice can narrow the
    /// witness lane again while it builds its extraction half.
    nominal_definitions_only: bool,
}

impl SampleBudget {
    /// The witness sentinel budget — a full walk of the tiny sample graph (every
    /// id), the clean define/is-a/directional-No core, NO non-edge class (its
    /// teeth are the corpus lane).
    pub const fn witness(seed: u64) -> Self {
        Self {
            seed,
            target_ids: usize::MAX,
            per_class: 4096,
            include_nonedge: false,
            include_directional_no: true,
            nominal_definitions_only: false,
        }
    }

    /// The corpus-lane budget — a bounded, seeded stride over the full corpus
    /// with every class enabled (the full faithfulness battery + honesty teeth).
    pub const fn corpus(seed: u64) -> Self {
        Self {
            seed,
            target_ids: 4000,
            per_class: 1500,
            include_nonedge: true,
            include_directional_no: true,
            nominal_definitions_only: false,
        }
    }

    fn stride(&self, count: usize) -> usize {
        if self.target_ids == 0 || count <= self.target_ids {
            1
        } else {
            (count / self.target_ids).max(1)
        }
    }
}

/// splitmix64 — a deterministic seed mixer for the non-edge partner offset.
fn mix(seed: u64, x: u64) -> u64 {
    let mut z = seed.wrapping_add(x).wrapping_add(0x9E37_79B9_7F4A_7C15);
    z = (z ^ (z >> 30)).wrapping_mul(0xBF58_476D_1CE4_E5B9);
    z = (z ^ (z >> 27)).wrapping_mul(0x94D0_49BB_1331_11EB);
    z ^ (z >> 31)
}

/// The label AND part of speech a concept realizes under — the POS drives the
/// slot surface (a verb concept is asked over its gerundial nominal) and the
/// determiner, so the generator authors question and Expected from the SAME
/// `(label, pos)` (the FIX-B both-halves law).
fn label_pos_of(reasoner: &dyn LexicalReasoner, id: ConceptId) -> Option<(String, LmfPos)> {
    reasoner
        .concept(id)
        .and_then(|c| c.lemmas().next().map(|s| (s.to_string(), c.pos())))
}

/// THE GENERATOR: walk `0 .. reasoner.concept_count()` once and emit a
/// `ProbeCase` per graph construct. Universe-agnostic — English ids, loaded
/// `.prx` ids and USC ids all decode through the same `concept(id)` and fall out
/// of the same loop. Pure over `&dyn LexicalReasoner`; the content is 100%
/// carried by the reasoner instance.
pub fn probe_cases<'r>(
    reasoner: &'r dyn LexicalReasoner,
    frames: &'r Frames,
    budget: SampleBudget,
) -> impl Iterator<Item = ProbeCase> + 'r {
    let count = reasoner.concept_count().value as usize;
    let stride = budget.stride(count);
    let subsumption = subsumption_kind();
    let opposition = opposition_relation_kind();

    let mut cases: Vec<ProbeCase> = Vec::new();
    let mut n_def = 0usize;
    let mut n_isa = 0usize;
    let mut n_dir = 0usize;
    let mut n_non = 0usize;

    let mut v = 0usize;
    while v < count {
        let id = ConceptId::new(v as u64);
        v += stride;

        let Some(view) = reasoner.concept(id) else {
            continue;
        };
        let Some(label) = view.lemmas().next().map(|s| s.to_string()) else {
            continue; // no lemma → no probe (honest skip)
        };

        // --- Definition: the concept's own gloss is the expected content. ---
        if n_def < budget.per_class
            && (!budget.nominal_definitions_only || view.pos() == LmfPos::Noun)
            && let Some(gloss) = view.definitions().next()
        {
            // An ADVERB has no grammatical bare-copula definitional reading
            // (neither "*what is a quickly" nor "*what is quickly" is
            // well-formed the way "what is a dog"/"what is able" are for a
            // noun/adjective) — Slice B's quoted-mention do-support frame
            // asks directly for the sense instead
            // (`.notes/chat-fix-c-build-state.md`).
            let question = if view.pos() == LmfPos::Adverb {
                frames.wh_mean(&label)
            } else {
                frames.wh_definition(&label, view.pos())
            };
            cases.push(ProbeCase {
                question,
                construct: Construct::Definition {
                    id,
                    source: reasoner.ontology_of_concept(id),
                },
                expected: Expected::ContainsGloss(gloss.to_string()),
            });
            n_def += 1;
        }

        // The surface this concept takes in a nominal slot — the SAME
        // realization the question will use, so every Expected property is
        // authored in the realizer's representation (a verb concept's slot
        // surface is its gerundial nominal).
        let slot = frames.nominal_slot(&label, view.pos());

        // --- IsA positive: every strict ancestor is a true is-a pair. ---
        if n_isa < budget.per_class {
            for anc in reasoner.ancestors(id) {
                if anc == id {
                    continue; // drop the reflexive head
                }
                let Some((anc_label, anc_pos)) = label_pos_of(reasoner, anc) else {
                    continue;
                };
                let anc_slot = frames.nominal_slot(&anc_label, anc_pos);
                cases.push(ProbeCase {
                    question: frames.polar_isa(&label, view.pos(), &anc_label, anc_pos),
                    construct: Construct::IsAPositive {
                        child: id,
                        ancestor: anc,
                    },
                    expected: Expected::Affirms {
                        subject: slot.clone(),
                        target: anc_slot,
                    },
                });
                n_isa += 1;
                if n_isa >= budget.per_class {
                    break;
                }
            }
        }

        // --- Directional-No: the REVERSE of a strict (direct) edge. ---
        if budget.include_directional_no && n_dir < budget.per_class {
            for &parent in reasoner.parents(id) {
                if parent == id {
                    continue;
                }
                let Some((parent_label, parent_pos)) = label_pos_of(reasoner, parent) else {
                    continue;
                };
                let parent_slot = frames.nominal_slot(&parent_label, parent_pos);
                cases.push(ProbeCase {
                    // Ask "is a <parent> a <child>?" — the strict edge runs the
                    // other way, so a faithful answer denies.
                    question: frames.polar_isa(&parent_label, parent_pos, &label, view.pos()),
                    construct: Construct::IsADirectionalNo { parent, child: id },
                    expected: Expected::DeniesDirectional {
                        subject: parent_slot,
                        object: slot.clone(),
                    },
                });
                n_dir += 1;
                if n_dir >= budget.per_class {
                    break;
                }
            }
        }

        // --- NonEdge: a seeded partner with no path either way. ---
        if budget.include_nonedge && n_non < budget.per_class && count > 1 {
            let offset = 1 + (mix(budget.seed, v as u64) as usize % (count - 1));
            let w = (v + offset) % count;
            let other = ConceptId::new(w as u64);
            if other != id
                && !reasoner.reaches(id, other, &subsumption)
                && !reasoner.reaches(other, id, &subsumption)
                && !reasoner.reaches(id, other, &opposition)
                && !reasoner.reaches(other, id, &opposition)
                && let Some((other_label, other_pos)) = label_pos_of(reasoner, other)
                && other_label != label
            {
                let other_slot = frames.nominal_slot(&other_label, other_pos);
                cases.push(ProbeCase {
                    question: frames.polar_isa(&label, view.pos(), &other_label, other_pos),
                    construct: Construct::NonEdge { a: id, b: other },
                    expected: Expected::DeniesOrAbstains {
                        known: vec![slot.clone(), other_slot],
                    },
                });
                n_non += 1;
            }
        }
    }

    cases.into_iter()
}

